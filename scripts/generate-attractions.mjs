import { readFileSync, writeFileSync } from "node:fs"
import path from "node:path"

const scriptsDir = import.meta.dirname
const root = path.join(scriptsDir, "..")

const poiPath = path.join(scriptsDir, "data", "schueberfouer_SCHUEBERFOUER_POI.geojson")
const facPath = path.join(scriptsDir, "data", "schueberfouer_SCHUEBERFOUER_FACILITIES.geojson")
const catPath = path.join(scriptsDir, "data", "schueberfouer_SCHUEBERFOUER_CATEGORIES.geojson")
const outPath = path.join(root, "src", "data", "attractions-generated.ts")

const categoryNames = new Map()
{
    const catData = JSON.parse(readFileSync(catPath, "utf8"))
    for (const f of catData.features) {
        categoryNames.set(f.properties.CATEGORY_ID, f.properties.CATEGORY_NAME_EN)
    }
}

function stripHtml(html) {
    if (!html) return ""
    return html
        .replaceAll(/<[^>]+>/g, " ")
        .replaceAll("&amp;", "&")
        .replaceAll("&lt;", "<")
        .replaceAll("&gt;", ">")
        .replaceAll("&quot;", '"')
        .replaceAll("&#39;", "'")
        .replaceAll(/\s+/g, " ")
        .trim()
}

function extractProducts(rawHtml) {
    if (!rawHtml) return []
    const liMatches = rawHtml.matchAll(/<li>(.*?)<\/li>/g)
    return Array.from(liMatches, (m) => stripHtml(m[1]))
}

function capitalize(s) {
    return s
        .split(" ")
        .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
        .join(" ")
}

function formatDescription(rawHtml) {
    const products = extractProducts(rawHtml)
    if (products.length === 0) return ""

    const items = products.map(capitalize)
    if (items.length <= 3) return items.join(", ")
    return `${items.slice(0, 4).join(", ")} and more`
}

function escapeTSString(s) {
    return s.replaceAll("\\", "\\\\").replaceAll("'", "\\'").replaceAll("\n", "\\n")
}

function loadPoiFeatures() {
    const poiData = JSON.parse(readFileSync(poiPath, "utf8"))
    const features = []
    for (const f of poiData.features) {
        const p = f.properties
        const coords = f.geometry.coordinates
        const catName = categoryNames.get(p.CATEGORY_ID)
        if (!catName) continue

        const group = p.GROUP_EN || undefined
        const desc = formatDescription(p.DESCRIPTION_EN)

        features.push({
            id: `poi-${p.OBJECTID}`,
            name: p.NAME_EN,
            category: catName,
            categoryId: p.CATEGORY_ID,
            description: desc,
            lat: coords[1],
            lng: coords[0],
            source: "geojson",
            photo: p.PHOTO || undefined,
            group,
        })
    }
    return features
}

function loadFacFeatures() {
    const facData = JSON.parse(readFileSync(facPath, "utf8"))
    const features = []
    for (const f of facData.features) {
        const p = f.properties
        const coords = f.geometry.coordinates
        const catName = categoryNames.get(p.CATEGORY_ID)
        if (!catName) continue

        const desc = stripHtml(p.DESCRIPTION_EN) || undefined
        features.push({
            id: `fac-${p.OBJECTID}`,
            name: p.NAME_EN,
            category: catName,
            categoryId: p.CATEGORY_ID,
            description: desc || p.NAME_EN,
            lat: coords[1],
            lng: coords[0],
            source: "geojson",
            photo: p.PHOTO || undefined,
            group: undefined,
        })
    }
    return features
}

function deduplicateNames(attractions) {
    const nameCounts = new Map()
    for (const a of attractions) {
        nameCounts.set(a.name, (nameCounts.get(a.name) || 0) + 1)
    }
    const nameIndexes = new Map()
    for (const a of attractions) {
        if (nameCounts.get(a.name) > 1) {
            const idx = (nameIndexes.get(a.name) || 0) + 1
            nameIndexes.set(a.name, idx)
            a.name = `${a.name} ${idx}`
        }
    }
}

function buildAttractions() {
    const attractions = [...loadPoiFeatures(), ...loadFacFeatures()]
    deduplicateNames(attractions)
    return attractions
}

const attractions = buildAttractions()

const source = `// Auto-generated by scripts/generate-attractions.mjs — do not edit
// Generated ${new Date().toISOString()}
import type { Attraction } from "./attractions"

export const ATTRACTIONS: Attraction[] = [
${attractions
    .map((a) => {
        const fields = [
            `    id: '${a.id}'`,
            `    name: '${escapeTSString(a.name)}'`,
            `    category: '${escapeTSString(a.category)}'`,
            `    categoryId: ${a.categoryId}`,
            `    description: '${escapeTSString(a.description || "")}'`,
            `    lat: ${a.lat}`,
            `    lng: ${a.lng}`,
            `    source: '${a.source}'`,
        ]
        if (a.photo) fields.push(`    photo: '${a.photo}'`)
        if (a.group) fields.push(`    group: '${escapeTSString(a.group)}'`)
        return `  {\n${fields.join(",\n")},\n  },`
    })
    .join("\n")}
]
`

writeFileSync(outPath, source, "utf8")
console.log(`Generated ${attractions.length} attractions → ${outPath}`)
